/**
 * Vendors the CHANGELOG.md of every package in the Astromesh ecosystem into
 * the docs site, one Starlight page per package plus a manifest the index
 * page reads.
 *
 * Packages in this monorepo are read from disk; the sibling repos are read
 * through the GitHub API (private ones need `GITHUB_TOKEN` or a logged-in
 * `gh`). The build never touches the network: run `npm run sync:changelogs`
 * when something ships and commit what it writes, like sync:catalog.
 */

