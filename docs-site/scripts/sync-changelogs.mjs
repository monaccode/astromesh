// `## [1.2.0] - 2026-11-04` (Keep a Changelog) and
// `## [1.2.0](https://…/compare/…) (2026-11-04)` (release-please) both count.
const RELEASE = /^## \[?v?([0-9][^\]\s]*)\]?(?:\([^)]*\))?\s*(?:[-–—]\s*|\()?(\d{4}-\d{2}-\d{2})?/;

/** The released versions in a Keep a Changelog file, newest first as written. */
export function parseReleases(markdown) {
  const out = [];
  for (const line of markdown.split(/\r?\n/)) {
    const m = RELEASE.exec(line);
    if (m) out.push({ version: m[1], date: m[2] ?? null });
  }
  return out;
}

/**
 * The changelog as a page body: the file's own `# Changelog` title goes
 * (Starlight renders the frontmatter title) and an empty `[Unreleased]` goes.
 * Versions stay at `##`, which is what Starlight treats as a page section.
 */
export function toPageBody(markdown) {
  const lines = markdown.replace(/\r\n/g, '\n').split('\n');
  const h1 = lines.findIndex((l) => /^# /.test(l));
  if (h1 !== -1) lines.splice(h1, 1);
  let body = lines.join('\n');
  body = body.replace(/^## \[?Unreleased\]?\s*\n+(?=## )/im, '');
  return `${body.trim()}\n`;
}

const yamlString = (s) => JSON.stringify(s);

export function toPage(source, markdown, releases, order = 1) {
  const latest = releases[0];
  const description = latest
    ? `Every release of ${source.package}. Latest: v${latest.version}${latest.date ? `, ${latest.date}` : ''}.`
    : `Every change to ${source.package}.`;
  return [
    '---',
    `title: ${yamlString(`${source.name} changelog`)}`,
    `description: ${yamlString(description)}`,
    'editUrl: false',
    'sidebar:',
    `  label: ${yamlString(source.name)}`,
    `  order: ${order}`,
    'tableOfContents:',
    '  minHeadingLevel: 2',
    '  maxHeadingLevel: 2',
    '---',
    '',
    `<!-- Generated by scripts/sync-changelogs.mjs from ${source.repo}${source.local ? `/${source.local}` : '/CHANGELOG.md'}. Do not edit by hand. -->`,
    '',
    toPageBody(markdown),
  ].join('\n');
}

function token() {
  if (process.env.GITHUB_TOKEN) return process.env.GITHUB_TOKEN;
  try {
    return execFileSync('gh', ['auth', 'token'], { encoding: 'utf8' }).trim();
  } catch {
    return null;
  }
}

async function fetchRemote(repo, auth) {
  const res = await fetch(`https://api.github.com/repos/monaccode/${repo}/contents/CHANGELOG.md`, {
    headers: {
      Accept: 'application/vnd.github.raw',
      'User-Agent': 'astromesh-docs-sync',
      ...(auth ? { Authorization: `Bearer ${auth}` } : {}),
    },
  });
  if (!res.ok) throw new Error(`${repo}: GitHub answered ${res.status} for CHANGELOG.md`);
  return res.text();
}

async function visibilityOf(repo, auth) {
  const res = await fetch(`https://api.github.com/repos/monaccode/${repo}`, {
    headers: { 'User-Agent': 'astromesh-docs-sync', ...(auth ? { Authorization: `Bearer ${auth}` } : {}) },
  });
  if (!res.ok) throw new Error(`${repo}: GitHub answered ${res.status}`);
  return (await res.json()).private ? 'private' : 'public';
}

export async function sync({ sources = SOURCES, pages = PAGES, manifest = MANIFEST } = {}) {
  const auth = token();
  mkdirSync(pages, { recursive: true });
  // A package dropped from SOURCES must not leave its page behind.
  for (const f of readdirSync(pages)) if (f.endsWith('.md')) rmSync(join(pages, f));

  const entries = [];
  for (const [i, source] of sources.entries()) {
    const markdown = source.local
      ? readFileSync(join(ASTROMESH_ROOT, source.local), 'utf8')
      : await fetchRemote(source.repo, auth);
    const releases = parseReleases(markdown);
    writeFileSync(join(pages, `${source.id}.md`), toPage(source, markdown, releases, i + 1));
    entries.push({
      id: source.id,
      name: source.name,
      package: source.package,
      repo: `https://github.com/monaccode/${source.repo}`,
      visibility: await visibilityOf(source.repo, auth),
      latest: releases[0] ?? null,
      releases,
    });
  }
  writeFileSync(
    manifest,
    `${JSON.stringify({ synced: new Date().toISOString().slice(0, 10), packages: entries }, null, 2)}\n`,
  );
  return entries;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  const entries = await sync();
  for (const e of entries) {
    console.log(`sync-changelogs: ${e.package.padEnd(18)} ${e.visibility.padEnd(7)} ${e.releases.length} release(s), latest ${e.latest ? `v${e.latest.version}` : '—'}`);
  }
}
